-- ==============================================================================
-- ПУНКТ 0: ПІДГОТОВКА ТА ВИПРАВЛЕННЯ СИСТЕМНИХ ОБМЕЖЕНЬ
-- Команда нижче дозволяє створювати локальних користувачів (без префікса C##).
-- Це обов'язково для версій Oracle 12c, 19c, 21c (фікс помилки ORA-65096).
-- ==============================================================================
ALTER SESSION SET "_ORACLE_SCRIPT" = true;

-- ==============================================================================
-- ПУНКТ 1: ОЧИЩЕННЯ (Для можливості повторного запуску скрипта без конфліктів)
-- Якщо об'єкти вже існують, ці команди їх видалять (фікс помилки ORA-01921).
-- При першому запуску помилки "does not exist" просто ігноруйте.
-- ==============================================================================
DROP USER user_ceo CASCADE;
DROP USER user_hr CASCADE;
DROP USER user_analyst CASCADE;
DROP ROLE role_analyst;
DROP ROLE role_hr_manager;
DROP ROLE role_project_admin;

-- ==============================================================================
-- ПУНКТ 2: СТВОРЕННЯ РОЛЕЙ (Завдання 3)
-- Роль — це об'єкт, який дозволяє згрупувати привілеї для певної посади.
-- ==============================================================================
CREATE ROLE role_analyst;      -- Роль для аналітичних звітів
CREATE ROLE role_hr_manager;   -- Роль для управління персоналом
CREATE ROLE role_project_admin;-- Роль для повного адміністрування проектів

-- ==============================================================================
-- ПУНКТ 3: НАДАННЯ ПРИВІЛЕЇВ РОЛЯМ (Завдання 4)
-- Надаємо доступ до об'єктів (таблиць), які ми створили в попередніх лабах.
-- ==============================================================================

-- 1. Права для Аналітика: тільки перегляд (SELECT)
GRANT SELECT ON SYSTEM.projects TO role_analyst;
GRANT SELECT ON SYSTEM.work_logs TO role_analyst;

-- 2. Права для HR-Менеджера: перегляд та редагування працівників
GRANT SELECT, INSERT, UPDATE ON SYSTEM.employees TO role_hr_manager;
GRANT SELECT ON SYSTEM.positions TO role_hr_manager;

-- 3. Права для Адміністратора Проектів: повний доступ до таблиці проектів
GRANT ALL PRIVILEGES ON SYSTEM.projects TO role_project_admin;

-- ==============================================================================
-- ПУНКТ 4: СТВОРЕННЯ КОРИСТУВАЧІВ (Завдання 1)
-- Створюємо реальні облікові записи для працівників фірми.
-- ==============================================================================
CREATE USER user_ceo IDENTIFIED BY CeoPass123;      -- Генеральний директор
CREATE USER user_hr IDENTIFIED BY HrPass123;        -- Менеджер з персоналу
CREATE USER user_analyst IDENTIFIED BY AnalystPass123; -- Бізнес-аналітик

-- Надаємо системний привілей CONNECT, щоб вони могли просто увійти в БД
GRANT CONNECT TO user_ceo, user_hr, user_analyst;

-- ==============================================================================
-- ПУНКТ 5: ПРИЗНАЧЕННЯ РОЛЕЙ ТА ПЕРСОНАЛЬНИХ ПРАВ (Завдання 2, 5)
-- ==============================================================================

-- Прив'язуємо користувачів до їхніх посадових ролей
GRANT role_project_admin TO user_ceo;
GRANT role_hr_manager TO user_hr;
GRANT role_analyst TO user_analyst;

-- ПЕРСОНАЛЬНИЙ ПРИВІЛЕЙ (Завдання 2):
-- Надаємо аналітику право оновлювати ТІЛЬКИ колонку 'description' у таблиці логів.
-- Це приклад обмеження доступу на рівні стовпців.
GRANT UPDATE (description) ON SYSTEM.work_logs TO user_analyst;

-- ==============================================================================
-- ПУНКТ 6: ПЕРЕВІРКА МЕХАНІЗМІВ ВІДКЛИКАННЯ ПРАВ (Завдання 6, 7)
-- Демонстрація того, що права, надані через роль та персонально, сумуються.
-- ==============================================================================

-- ТЕСТ 1: Надаємо особистий SELECT і відразу забираємо його.
GRANT SELECT ON SYSTEM.projects TO user_analyst;
REVOKE SELECT ON SYSTEM.projects FROM user_analyst;
-- ПОЯСНЕННЯ: Користувач все ще може робити SELECT, бо право залишилося в його РОЛІ.

-- ТЕСТ 2: Повністю забираємо роль у аналітика.
REVOKE role_analyst FROM user_analyst;
-- ПОЯСНЕННЯ: Тепер SELECT перестане працювати, але персональний UPDATE (description)
-- все ще діятиме, бо він був наданий особисто користувачу, а не через роль.

-- ==============================================================================
-- ПУНКТ 7: ПЕРЕВІРКА ТА КОНТРОЛЬ (Завдання 8)
-- Використовуємо системний словник для перевірки результатів.
-- ==============================================================================

-- Перегляд створених користувачів та їхнього статусу
SELECT username, account_status, created
FROM dba_users
WHERE username IN ('USER_CEO', 'USER_HR', 'USER_ANALYST');

-- Перегляд наданих ролей (щоб переконатися, що CEO та HR мають свої ролі)
SELECT grantee, granted_role FROM dba_role_privs
WHERE grantee IN ('USER_CEO', 'USER_HR');